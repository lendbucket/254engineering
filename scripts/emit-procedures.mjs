/**
 * Writes src/content/procedures.ts from docs/workflows.md. Run it after any
 * change to the workflow map, then commit what it wrote:
 *
 *   node scripts/emit-procedures.mjs
 *
 * scripts/proofs/the-procedures-are-the-workflow-map.mjs parses the map again
 * and fails until the module agrees with it. See
 * scripts/lib/workflow-procedures.mjs for what a procedure is.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { parseProcedures } from "./lib/workflow-procedures.mjs";

const procedures = parseProcedures(readFileSync("docs/workflows.md", "utf8"));

writeFileSync(
  "src/content/procedures.ts",
  `/**
 * GENERATED by scripts/emit-procedures.mjs from docs/workflows.md. Do not edit.
 *
 * The firm's written procedures, 254-OPS-001 onward, one per workflow in the
 * map and numbered by it (W4, Robert 2026-10-26). The map is the one home of
 * the text; scripts/proofs/the-procedures-are-the-workflow-map.mjs parses it
 * again and fails on any difference.
 */
export type ProcedureStep = {
  n: string;
  screen: string;
  /** The portal screens named in the Screen cell, as routes. */
  routes: string[];
  who: string;
  sees: string;
  does: string;
  next: string;
  told: string;
  record: string;
  marks: string;
};

export type Procedure = {
  workflow: string;
  number: string;
  title: string;
  /** The role section of the map it sits in. */
  section: string;
  steps: ProcedureStep[];
  notes: string[];
};

export const PROCEDURES: Procedure[] = ${JSON.stringify(procedures, null, 2)};
`,
);
console.log(`wrote src/content/procedures.ts: ${procedures.length} procedures, ${procedures.reduce((n, p) => n + p.steps.length, 0)} steps`);
