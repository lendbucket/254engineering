// Transcribes the engineer's protocols that arrive as Word files into
// src/content/protocols/docx-received.ts. Run from the repository root:
//
//   node scripts/transcribe-docx-protocols.mjs
//
// Operator ruling, 2026-10-10: the .docx is the source of record. Every line
// written is the document's own, read through documentText() in
// scripts/lib/protocol-source.mjs from the file itself; nothing is reworded,
// and the engineer's punctuation,
// including his long dashes, is carried exactly (CLAUDE.md section 3).
//
// THIS SCRIPT IS NOT THE PROOF. protocol-registry-audit section 9 reads each
// .docx itself and compares, never importing anything from here.
//
// WHAT IS TRANSCRIBED, AND WHAT IS NOT YET. Each document's whole text, its
// header fields, and the line it belongs to. Its intake, checklist and
// decision rules are NOT parsed into structure here, as the v1.1 transcriber
// does from the PDFs: structure is what a protocol needs to RUN, and a
// protocol runs only once the engineer has signed it and it moves into
// PROTOCOL_ENTRIES. That move is waiting on the operator's ruling (run report,
// item 4). Until then each is a document the firm holds, proved word for word.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
/*
 * The repository's one reader of a protocol's source, which has read .docx
 * through word/document.xml since 2026-10-06 and is proved against a Word file
 * the audit builds with a known answer. A second reader was written for this
 * and deleted on finding this one: two readers of one document are two answers.
 */
import { documentText } from "./lib/protocol-source.mjs";

const docxLines = (path) => {
  const read = documentText(path);
  if (!read.ok) throw new Error(read.why);
  return read.text.split("\n");
};

const DIR = "docs/protocols/incoming/v1.2";
const DOCS = [
  {
    constName: "WP001_V1_2",
    file: "254-WP-001_Windstorm_Inspection_Protocol_v1_2.docx",
    serviceSlug: "windstorm-wpi-8",
    serviceTier: "ongoing",
  },
  {
    constName: "FC001_V1_0",
    file: "254-FC-001_Foundation_Certification_Protocol_v1.0.docx",
    /*
     * The line FC-001 governs, by the operator's ruling of 2026-10-10 ("FC-001
     * now exists for the foundation line"). Its title says certification of
     * existing foundations; how the line is sold is reported, not decided here.
     */
    serviceSlug: "foundation-inspections",
    serviceTier: null,
  },
];

const KEYS = ["Title", "Document number", "Version", "Issue date", "Prepared by", "Approval", "Applies to", "Supersedes"];
const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
const iso = (s) => {
  const m = String(s).match(/^([A-Z][a-z]+) (\d{1,2}), (\d{4})$/);
  if (!m || !MONTHS.includes(m[1])) throw new Error(`not a date the document writes: ${s}`);
  return `${m[3]}-${String(MONTHS.indexOf(m[1]) + 1).padStart(2, "0")}-${m[2].padStart(2, "0")}`;
};

const out = [];
for (const d of DOCS) {
  const path = `${DIR}/${d.file}`;
  const sha256 = createHash("sha256").update(readFileSync(path)).digest("hex");
  const text = docxLines(path).filter((l) => l.trim() !== "");
  const end = text.indexOf("1. Purpose");
  if (text[1] === undefined || end < 0) throw new Error(`${d.file}: no header table before "1. Purpose"`);
  const head = {};
  for (let i = 0; i < end; i += 1) {
    if (KEYS.includes(text[i]) && i + 1 < end && !KEYS.includes(text[i + 1])) head[text[i]] = text[i + 1];
  }
  const missing = KEYS.filter((k) => !(k in head));
  if (missing.length) throw new Error(`${d.file}: header has no ${missing.join(", ")}`);
  const firm = (head["Prepared by"].match(/, (254 Engineering[^,]*)$/) ?? [])[1] ?? null;
  out.push({
    constName: d.constName,
    declaration: {
      documentNumber: head["Document number"],
      version: head["Version"],
      title: head["Title"],
      issueDate: iso(head["Issue date"]),
      preparedBy: head["Prepared by"],
      approval: head["Approval"],
      appliesTo: head["Applies to"],
      supersedes: head["Supersedes"],
      firmNameOnDocument: firm,
      serviceSlug: d.serviceSlug,
      serviceTier: d.serviceTier,
      sourceFile: path,
      sourceSha256: sha256,
      text,
    },
  });
  console.log(JSON.stringify({ doc: head["Document number"], version: head["Version"], lines: text.length, sha256, preparedBy: head["Prepared by"] }));
}

const src = `/**
 * ===========================================================================
 * PROTOCOLS RECEIVED AS WORD FILES, NOT SIGNED. Transcribed, and they drive
 * nothing. Operator ruling, 2026-10-10.
 * ===========================================================================
 *
 * GENERATED by scripts/transcribe-docx-protocols.mjs from the .docx files in
 * ${DIR}, which are the source of record, read through documentText() in
 * scripts/lib/protocol-source.mjs. Do not edit by hand: every string is the
 * engineer's own, punctuation included (CLAUDE.md section 3).
 *
 * PROVED by protocol-registry-audit section 9, against each .docx read
 * independently, by a SHA-256 pinned in that audit as a literal: the whole text,
 * word for word, in both directions.
 *
 * TEXT, NOT YET STRUCTURE. These carry the document's text and header. Their
 * intake, checklist and decision rules are parsed into structure when the
 * engineer signs and the protocol moves into PROTOCOL_ENTRIES, which waits on
 * the operator's ruling. Until then nothing reads them except that audit and
 * the migration that enters each as a draft.
 */

export type DocxProtocol = {
  documentNumber: string;
  version: string;
  title: string;
  issueDate: string;
  preparedBy: string;
  approval: string;
  appliesTo: string;
  supersedes: string;
  firmNameOnDocument: string | null;
  serviceSlug: string;
  serviceTier: string | null;
  sourceFile: string;
  sourceSha256: string;
  text: readonly string[];
};

${out.map((o) => `export const ${o.constName}: DocxProtocol = ${JSON.stringify(o.declaration, null, 2)};`).join("\n\n")}

export const DOCX_RECEIVED_PROTOCOLS: readonly DocxProtocol[] = [${out.map((o) => o.constName).join(", ")}];
`;
writeFileSync("src/content/protocols/docx-received.ts", src, "utf8");
console.log("wrote src/content/protocols/docx-received.ts");
