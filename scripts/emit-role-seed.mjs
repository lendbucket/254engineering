/**
 * Emit the role seed SQL from DEFAULT_ROLES.
 *
 *   npx tsx scripts/emit-role-seed.mjs
 *
 * The migration's seed is GENERATED rather than typed, because the three
 * existing roles must grant exactly what they granted the day before it ran.
 * A retyped list is a second chance to get that wrong, and the mistake would
 * look like a decision somebody made.
 *
 * Run it, paste the output into the migration, and roles-audit then asserts the
 * database matches DEFAULT_ROLES so the two cannot drift afterwards either.
 */
import { DEFAULT_ROLES } from "../src/lib/ops-authz.ts";

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

console.log("-- Generated by scripts/emit-role-seed.mjs from DEFAULT_ROLES. Do not hand edit.");
console.log("insert into eng_roles (key, name, landing_path, is_system) values");
console.log(
  DEFAULT_ROLES.map(
    (r) => `  (${q(r.key)}, ${q(r.name)}, ${q(r.landingPath)}, ${r.isSystem})`,
  ).join(",\n") + "\non conflict (key) do nothing;",
);
console.log("");
console.log("insert into eng_role_grants (role_key, action) values");

const rows = [];
for (const role of DEFAULT_ROLES) {
  for (const action of [...role.grants].sort()) {
    rows.push(`  (${q(role.key)}, ${q(action)})`);
  }
}
console.log(rows.join(",\n") + "\non conflict (role_key, action) do nothing;");

console.log("");
console.log(`-- ${DEFAULT_ROLES.length} roles, ${rows.length} grants.`);
for (const r of DEFAULT_ROLES) {
  console.log(`--   ${r.key.padEnd(18)} ${String(r.grants.length).padStart(2)} grants  -> ${r.landingPath}`);
}
