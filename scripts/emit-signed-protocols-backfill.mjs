/**
 * WRITES SECTION 7 OF 0081: THE SIGNATURES ALREADY ON RECORD, PUT IN FORCE ONCE.
 *
 *   npx tsx --conditions=react-server scripts/emit-signed-protocols-backfill.mjs          print it
 *   npx tsx --conditions=react-server scripts/emit-signed-protocols-backfill.mjs --write  write it into 0081
 *
 * Operator ruling, 2026-10-22: signatures already on record go in force once,
 * inside 0081, in the production sitting, and the read-back lists exactly which
 * protocols went in force and why. No scheduled step.
 *
 * WHAT THE DATABASE CANNOT KNOW AND THIS FILE HANDS IT, for each signable
 * protocol except 254-WP-001 (deferred by ruling, it shares windstorm-wpi-8
 * with 254-WS-001 and needs a signed scope addendum):
 *   - the transcription's digest a valid signature carries, computed exactly as
 *     src/lib/protocol-sign.ts transcriptionSha256 computes it;
 *   - the checklist items to seed, from protocolItemRowsFor, the same rows
 *     approveProtocol seeds;
 *   - which signers may put it in force: the register's engineers whose licence
 *     is current and whose sealsOnly covers the discipline, AS SHA-256 HASHES of
 *     the licence number, so no licence number is written into a public file.
 *
 * It refuses to write anything when a protocol it should cover has no items in
 * the registry, because a signature that cannot go in force at the sitting is
 * the exact gap the ruling closes. Every protocol it covers gets one audit
 * event, in force or not, naming the reason, which is the read-back.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const MIGRATION = "supabase/migrations/0081_a_signature_puts_its_protocol_in_force.sql";
const BEGIN = "-- BEGIN GENERATED BY scripts/emit-signed-protocols-backfill.mjs. DO NOT EDIT BY HAND.";
const END = "-- END GENERATED";
const { SIGNABLE_PROTOCOLS, HELD_OUT_OF_FORCE: DEFERRED } = await import("../src/content/protocols/signable.ts");
const { signedProtocolItemRows } = await import("../src/lib/protocol-run.ts");
const { verifiedEngineers } = await import("../src/config/credentials.ts");
const { licenceIsCurrentToday } = await import("../src/lib/launch.ts");

const sha = (s) => createHash("sha256").update(s, "utf8").digest("hex");
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

const signers = verifiedEngineers
  .filter((e) => licenceIsCurrentToday(e.expires))
  .flatMap((e) => e.sealsOnly.map((d) => ({ licenceSha: sha(e.licenseNumber), discipline: d })));
if (signers.length === 0) {
  console.error("No engineer on the register has a current licence, so no signature could go in force. Nothing written.");
  process.exit(1);
}

const blocks = [];
const missing = [];
for (const p of SIGNABLE_PROTOCOLS) {
  if (DEFERRED[p.documentNumber]) continue;
  const items = signedProtocolItemRows(p.documentNumber, p.version);
  if (!items || items.length === 0) {
    missing.push(`${p.documentNumber} v${p.version}`);
    continue;
  }
  const json = JSON.stringify(items);
  if (json.includes("$items$")) throw new Error(`${p.documentNumber}: its items carry the quoting tag`);
  blocks.push({ doc: p.documentNumber, version: p.version, digest: sha(p.text.join("\n")), json, count: items.length });
}
if (missing.length) {
  console.error(`These signable protocols have no items in the registry, so their signatures could not go in force: ${missing.join(", ")}. Nothing written.`);
  process.exit(1);
}

const out = [BEGIN];
out.push("/*");
out.push(" * For each protocol: the live signature on record, if any, is put in force when");
out.push(" * its digest is the transcription's and its signer may seal the discipline;");
out.push(" * otherwise it stays as it is. Either way one audit event names the outcome and");
out.push(" * the reason, action protocol.in_force_at_0081, and that is the read-back.");
out.push(` * Deferred and not covered: ${Object.entries(DEFERRED).map(([d, why]) => `${d}, ${why}`).join("; ")}.`);
out.push(" */");
out.push("create temporary table eng_0081_signers (licence_sha256 text, discipline text) on commit drop;");
out.push(
  `insert into eng_0081_signers values ${signers.map((s) => `(${lit(s.licenceSha)}, ${lit(s.discipline)})`).join(", ")};`,
);
for (const b of blocks) {
  out.push("");
  out.push(`-- ${b.doc} v${b.version}: ${b.count} items, transcription sha256 ${b.digest}`);
  out.push("do $backfill$");
  out.push("declare");
  out.push("  v_act      record;");
  out.push("  v_template record;");
  out.push("  v_licence  text;");
  out.push("  v_outcome  text;");
  out.push("  v_why      text;");
  out.push("begin");
  out.push("  select id, content_sha256, sealed_by into v_act from eng_seal_acts");
  out.push(`   where kind = 'protocol' and protocol_document = ${lit(b.doc)} and protocol_version = ${lit(b.version)} and voided_at is null;`);
  out.push(`  select id, status, requires_discipline into v_template from eng_protocol_templates where document_number = ${lit(b.doc)} and version_label = ${lit(b.version)};`);
  out.push("  if v_act.id is null then");
  out.push("    v_outcome := 'not in force'; v_why := 'no live signature on record';");
  out.push(`  elsif v_act.content_sha256 is distinct from ${lit(b.digest)} then`);
  out.push("    v_outcome := 'not in force'; v_why := 'the signature does not cover the transcription in code; it reads as void';");
  out.push("  else");
  out.push("    select license_number into v_licence from eng_profiles where id = v_act.sealed_by;");
  out.push("    if not exists (select 1 from eng_0081_signers s where s.licence_sha256 = encode(sha256(convert_to(coalesce(btrim(v_licence), ''), 'UTF8')), 'hex') and s.discipline = v_template.requires_discipline) then");
  out.push("      v_outcome := 'not in force'; v_why := 'the signer is not an engineer on the register with a current licence who seals ' || coalesce(v_template.requires_discipline, 'an undeclared discipline');");
  out.push("    else");
  out.push(`      v_outcome := eng_put_signed_protocol_in_force(v_act.id, btrim(v_licence), $items$${b.json}$items$::jsonb);`);
  out.push("      v_why := 'a live signature whose digest is the transcription in code, by an engineer on the register';");
  out.push("    end if;");
  out.push("  end if;");
  out.push("  insert into eng_audit_events (action, entity_type, entity_id, summary, diff)");
  out.push("  values ('protocol.in_force_at_0081', 'protocol', coalesce(v_template.id::text, " + lit(b.doc) + "),");
  out.push(`    ${lit(`${b.doc} v${b.version}: `)} || v_outcome || ', ' || v_why,`);
  out.push(`    jsonb_build_object('document', ${lit(b.doc)}, 'version', ${lit(b.version)}, 'outcome', v_outcome, 'why', v_why, 'seal_act_id', v_act.id));`);
  out.push("end;");
  out.push("$backfill$;");
}
out.push(END);
const region = out.join("\n");

if (process.argv.includes("--write")) {
  const text = readFileSync(MIGRATION, "utf8");
  const a = text.indexOf(BEGIN);
  const z = text.indexOf(END);
  if (a < 0 || z < a) throw new Error("the generated markers are not in 0081; nothing written");
  writeFileSync(MIGRATION, text.slice(0, a) + region + text.slice(z + END.length));
  console.log(`wrote section 7: ${blocks.length} protocols (${blocks.map((b) => b.doc).join(", ")}), ${signers.length} signer-discipline pair(s)`);
} else {
  console.log(region);
}
