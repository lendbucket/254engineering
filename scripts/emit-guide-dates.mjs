/**
 * Writes src/content/guide-dates.ts from git. Run it after committing a change
 * to any guide page's words, then commit what it wrote:
 *
 *   node scripts/emit-guide-dates.mjs
 *
 * guide-dates-audit fails until the file agrees with git again. See
 * scripts/lib/guide-dates.mjs for what a page's history is.
 */
import { writeFileSync } from "node:fs";
import { deriveGuideDates } from "./lib/guide-dates.mjs";

const dates = deriveGuideDates();
const body = Object.entries(dates)
  .map(([path, d]) => `  ${JSON.stringify(path)}: { datePublished: ${JSON.stringify(d.datePublished)}, dateModified: ${JSON.stringify(d.dateModified)} },`)
  .join("\n");

writeFileSync(
  "src/content/guide-dates.ts",
  `/**
 * GENERATED by scripts/emit-guide-dates.mjs from git history. Do not edit.
 *
 * The publication and modification dates of the fifteen guide pages, for their
 * Article schema (Robert, 2026-10-25). Each is the oldest and newest commit in
 * the history of the lines that hold that page's own words.
 * scripts/guide-dates-audit.mjs derives them again from git and fails on any
 * difference, so a guide edited without re-running the emitter is named.
 */
export const GUIDE_DATES: Record<string, { datePublished: string; dateModified: string }> = {
${body}
};
`,
);
console.log(`wrote src/content/guide-dates.ts: ${Object.keys(dates).length} guide pages`);
