/**
 * Writes src/content/guide-dates.ts from git. Run it after committing a change
 * to any guide page's or insight post's words, then commit what it wrote:
 *
 *   node scripts/emit-guide-dates.mjs
 *
 * guide-dates-audit fails until the file agrees with git again. See
 * scripts/lib/guide-dates.mjs for what a page's and a post's history is.
 */
import { writeFileSync } from "node:fs";
import { deriveGuideDates, derivePostDates } from "./lib/guide-dates.mjs";

const guides = deriveGuideDates();
const posts = derivePostDates();
const rows = (o) =>
  Object.entries(o)
    .map(([k, d]) => `  ${JSON.stringify(k)}: { datePublished: ${JSON.stringify(d.datePublished)}, dateModified: ${JSON.stringify(d.dateModified)} },`)
    .join("\n");

writeFileSync(
  "src/content/guide-dates.ts",
  `/**
 * GENERATED by scripts/emit-guide-dates.mjs from git history. Do not edit.
 *
 * The publication and modification dates of the fourteen guide pages, for their
 * Article schema, and of every insight post (Robert, 2026-10-25). Each is the
 * oldest and newest commit in the history of the lines that hold that page's
 * own words; a post's are Chicago days, and a commit that changes only a date
 * line does not count. scripts/guide-dates-audit.mjs derives them again from
 * git and fails on any difference, and on any typed post date that disagrees.
 */
export const GUIDE_DATES: Record<string, { datePublished: string; dateModified: string }> = {
${rows(guides)}
};

export const POST_DATES: Record<string, { datePublished: string; dateModified: string }> = {
${rows(posts)}
};
`,
);
console.log(`wrote src/content/guide-dates.ts: ${Object.keys(guides).length} guide pages, ${Object.keys(posts).length} posts`);
