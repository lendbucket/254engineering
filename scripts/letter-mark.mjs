// The mark printed at the top of every sealed letter, and the module that
// carries its bytes.
//
//   node scripts/letter-mark.mjs
//
// Operator ruling, 2026-10-22: the firm logo heads every sealed letter, a
// version without "SERVICES"; until a corrected file exists, the 254 mark alone
// with no tagline. It is EMBEDDED in the letter, never loaded from a URL, and
// its checksum is recorded with the sealed document.
//
// THE SAME CROP THE ICONS USE. scripts/brand-rasters.mjs crops the delivered
// lockup to its numeral band (the gold rule sits at about 72 percent of the
// height and the "254 ENGINEERING SERVICES" descriptor is below it) and trims
// it. This does that to the navy artwork, brand-assets/logo.png, so the mark
// prints dark on the white page, and scales it to 600 pixels wide, which is
// 400 dots per inch at the inch and a half it is drawn at.
//
// It writes two files and both are committed:
//   brand-assets/letter-mark.png                 the image, for a person to look at
//   src/content/letters/letterhead-mark.ts       its bytes and SHA-256, which the
//                                                letter embeds and the seal records
// letter-mark-audit re-derives the module from the PNG, so the two cannot drift.
//
// WHEN THE CORRECTED LOGO ARRIVES: replace brand-assets/logo.png (or point SRC
// at the new file), set NUMERAL_BAND to 1 if the new file has no descriptor to
// crop away, and rerun.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SRC = path.join(process.cwd(), "brand-assets", "logo.png");
const NUMERAL_BAND = 0.7;
const WIDTH = 600;

const meta = await sharp(SRC).metadata();
const band = await sharp(SRC)
  .extract({ left: 0, top: 0, width: meta.width, height: Math.round(meta.height * NUMERAL_BAND) })
  .toBuffer();
const tight = await sharp(band).trim().toBuffer();
const png = await sharp(tight).resize({ width: WIDTH }).png({ compressionLevel: 9 }).toBuffer();
const out = await sharp(png).metadata();
const sha256 = createHash("sha256").update(png).digest("hex");

writeFileSync(path.join(process.cwd(), "brand-assets", "letter-mark.png"), png);

const lines = [
  "/**",
  " * THE MARK AT THE TOP OF EVERY SEALED LETTER, AS BYTES. GENERATED by",
  " * scripts/letter-mark.mjs from brand-assets/logo.png; do not edit by hand.",
  " *",
  " * Operator ruling, 2026-10-22: embedded in the letter, never loaded from a",
  " * URL, and its checksum recorded with the sealed document. The 254 mark alone",
  " * with no tagline until a corrected logo without \"SERVICES\" is supplied.",
  " */",
  "export const LETTERHEAD_MARK = {",
  `  widthPx: ${out.width},`,
  `  heightPx: ${out.height},`,
  `  sha256: "${sha256}",`,
  `  pngBase64: "${png.toString("base64")}",`,
  "} as const;",
  "",
];
writeFileSync(path.join(process.cwd(), "src", "content", "letters", "letterhead-mark.ts"), lines.join("\n"));
console.log(`letter mark: ${out.width} x ${out.height}, ${png.byteLength} bytes, sha256 ${sha256}`);
