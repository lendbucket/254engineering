-- --------------------------------------------------- profiles point at a row
--
-- eng_profiles.role keeps its NAME and its VALUES. 'admin', 'engineer' and
-- 'field_tech' are now the keys of seeded rows rather than members of a check
-- constraint, so NO PROFILE ROW IS REWRITTEN and no session is invalidated.
--
-- Production holds exactly one profile, an active administrator, and it lands
-- on the administrator role without a gap: the row it points at was inserted
-- above, in the same transaction, before the constraint below is swapped.
-- THE OTHER ROLE CONSTRAINT STAYS, AND WAS CHECKED AGAINST THE NEW ROLES.
--
-- eng_profiles_role_fields says license_number and tdi_appointment belong only
-- to an engineer, and certification_status and coverage_counties only to a
-- field technician. It keys off the same role values and is NOT dropped: it is
-- still true, and it is what stops a salesperson row carrying a licence number.
--
-- Verified rather than assumed: those columns default to NULL, and
-- coverage_counties defaults to '{}', so a dispatcher, sales, customer service
-- or read only profile created with defaults satisfies it. A new role does not
-- need a change here.
alter table eng_profiles drop constraint if exists eng_profiles_role_check;

alter table eng_profiles
  add constraint eng_profiles_role_fkey
  foreign key (role) references eng_roles (key) on update cascade;

comment on column eng_profiles.role is
  'The role key, now a foreign key into eng_roles rather than a check constraint. Values are unchanged from before Phase 10 Section 2.';
