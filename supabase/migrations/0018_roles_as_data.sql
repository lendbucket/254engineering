-- ===========================================================================
-- 0018: roles and grants become data
--
-- Phase 10 Section 2. The platform had three roles compiled into a TypeScript
-- union and a static matrix. A firm that hires a coordinator, a salesperson or
-- a customer service representative needs more, and a buyer of this business
-- needs to see that access is governed rather than assumed.
--
-- WHAT DOES NOT BECOME DATA, AND THAT IS THE POINT
-- ------------------------------------------------
-- Sealing, the four review decisions, and authoring or publishing a protocol
-- are NOT in this schema. There is no row that grants them and no column that
-- represents them. They are bound in code to holding the engineer role, because
-- a seal represents a Texas PE licence and a licence is not something a
-- permission screen may confer.
--
-- Operator ruling, 2026-09-04: grantable-but-excluded leaves an exclusion
-- somebody can delete; unrepresentable leaves nothing to delete. The compiler
-- enforces it, in scripts/proofs/licensed-actions-are-unrepresentable.ts, which
-- fails the project typecheck the day one of them becomes grantable.
-- ===========================================================================

create table if not exists eng_roles (
  key           text primary key,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),

  name          text not null,

  /*
   * Where somebody holding this role lands after signing in.
   *
   * NOT NULL, so creating a role without one is impossible rather than
   * discouraged. Operator ruling: an owner created role silently inheriting
   * somebody else's home screen is the kind of thing nobody notices until a
   * salesperson lands on the review queue and wonders what it is. A default
   * would have made that the quiet behaviour.
   */
  landing_path  text not null,

  /*
   * A system role cannot be deleted or rekeyed. Its GRANTS are still the
   * owner's to change, because that is a decision about the firm.
   *
   * The engineer key matters most: holdsLicence compares against it, so
   * renaming it would quietly detach the licence from the people holding it.
   */
  is_system     boolean not null default false,

  description   text
);

create table if not exists eng_role_grants (
  role_key      text not null references eng_roles (key) on update cascade on delete cascade,
  action        text not null,
  created_at    timestamptz not null default now(),
  primary key (role_key, action)
);

create index if not exists eng_role_grants_role_idx on eng_role_grants (role_key);

alter table eng_roles enable row level security;
alter table eng_role_grants enable row level security;

drop trigger if exists eng_roles_touch on eng_roles;
create trigger eng_roles_touch before update on eng_roles
  for each row execute function eng_touch_updated_at();

comment on table eng_roles is
  'Roles as data, owner creatable. The licence bound capabilities are deliberately NOT representable here: see the header of 0018 and scripts/proofs.';
comment on column eng_roles.landing_path is
  'Where this role lands after signing in. NOT NULL so a new role cannot silently inherit somebody else''s home screen.';
comment on column eng_roles.is_system is
  'Cannot be deleted or rekeyed. Grants remain editable. The engineer key is compared against in code, so renaming it would detach the licence.';

