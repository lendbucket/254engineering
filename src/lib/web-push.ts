import "server-only";
import { createPrivateKey, sign } from "node:crypto";
import { base64url, fromBase64url, vapidSigningInput } from "./offer-push-rules";

/**
 * SENDING A PUSH WITH NO PAYLOAD, SIGNED WITH THE FIRM'S VAPID KEY (RFC 8292).
 * Robert's T9, 2026-11-07. No library: the signature is ES256 by Node's own
 * crypto, and a push with no body needs nothing else (offer-push-rules.ts says
 * why there is no body).
 *
 * THE KEYS. VAPID_PUBLIC_KEY is the uncompressed P-256 point, base64url, which
 * the phone is given to subscribe with. VAPID_PRIVATE_KEY is the private scalar,
 * base64url. VAPID_SUBJECT is a mailto: address for the firm. All three are
 * declared in src/config/credential-inventory.ts and generated by
 * scripts/generate-vapid-keys.mjs, which Robert runs himself so the private key
 * is never in a session's output. Absent any of the three, push is not
 * available, the screen says so, and email carries the offer as before.
 */

export type VapidConfig = { publicKey: string; privateKey: string; subject: string };

export function vapidConfig(): VapidConfig | null {
  const publicKey = process.env.VAPID_PUBLIC_KEY?.trim();
  const privateKey = process.env.VAPID_PRIVATE_KEY?.trim();
  const subject = process.env.VAPID_SUBJECT?.trim();
  if (!publicKey || !privateKey || !subject || !subject.startsWith("mailto:")) return null;
  return { publicKey, privateKey, subject };
}

/** The Authorization header for one endpoint: `vapid t=<jwt>, k=<public key>`. */
export function vapidAuthorization(endpoint: string, config: VapidConfig, nowSeconds = Math.floor(Date.now() / 1000)): string {
  const point = fromBase64url(config.publicKey);
  if (point.length !== 65 || point[0] !== 4) throw new Error("VAPID_PUBLIC_KEY is not an uncompressed P-256 point.");
  const key = createPrivateKey({
    key: {
      kty: "EC",
      crv: "P-256",
      d: config.privateKey,
      x: base64url(point.slice(1, 33)),
      y: base64url(point.slice(33, 65)),
    },
    format: "jwk",
  });
  const input = vapidSigningInput(endpoint, config.subject, nowSeconds);
  const signature = sign("sha256", new TextEncoder().encode(input), { key, dsaEncoding: "ieee-p1363" });
  return `vapid t=${input}.${base64url(new Uint8Array(signature))}, k=${config.publicKey}`;
}

/** Send one empty push. Resolves to the push service's status, or null when the request itself failed. */
export async function sendEmptyPush(endpoint: string, config: VapidConfig): Promise<number | null> {
  try {
    const res = await fetch(endpoint, {
      method: "POST",
      headers: {
        Authorization: vapidAuthorization(endpoint, config),
        TTL: "3600",
        Urgency: "high",
        "Content-Length": "0",
      },
    });
    return res.status;
  } catch {
    return null;
  }
}
